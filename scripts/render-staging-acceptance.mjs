#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";

const sourcePath = "docs/v2-new-build/operator/staging-acceptance.json";
const outputPath = "docs/v2-new-build/operator/staging-acceptance.md";
const manifest = JSON.parse(await readFile(sourcePath, "utf8"));
const lines = [
  "# WeVid Staging Acceptance Matrix",
  "",
  "Status: accepted",
  "Scope: operator-readable view of the canonical machine-readable staging acceptance manifest",
  "Last updated: 2026-08-24",
  "Source of truth: no — generated from `staging-acceptance.json`",
  "",
  "| Journey | Role | Route | Provider | Status | Blocker |",
  "| --- | --- | --- | --- | --- | --- |",
  ...manifest.journeys.map((journey) => `| \`${journey.id}\` | ${journey.role} | \`${journey.uiRoute}\` | ${journey.providerDependency.join(", ") || "none"} | ${journey.status} | ${journey.blockerClass} |`),
  "",
  "Regenerate with `pnpm staging:acceptance:render`. Do not edit this file by hand.",
  ""
];
await writeFile(outputPath, lines.join("\n"));
console.log(`Rendered ${manifest.journeys.length} journeys to ${outputPath}`);
